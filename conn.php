/**
 * List all /doc_vic entries as a clean array (works if node is a map or array)
 */
function fb_list_doc_vic(): array {
    $node = fb_get('/doc_vic');
    if (!$node) return [];
    if (is_array($node)) {
        // If array had null holes, filter them out
        if (array_keys($node) === range(0, count($node) - 1)) {
            return array_values(array_filter($node, fn($v) => is_array($v)));
        }
        // If object map: return values
        return array_values(array_filter($node, fn($v) => is_array($v)));
    }
    return [];
}
